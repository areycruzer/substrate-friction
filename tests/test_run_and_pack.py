def test_pytest_id_mapping():
    assert to_pytest_id("tests.test_gate::test_x") == \
        "tests/test_gate.py::test_x"
    assert to_pytest_id("pkg.mod::Cls.method") == \
        "pkg/mod.py::Cls.method"
    assert to_pytest_id("test_core::test_helper") == "test_core.py::test_helper"
    assert to_pytest_id("no_separator") is None
    assert to_pytest_id("..traversal::x") is None       # never guess paths


def test_build_plan_always_ships_the_fallback():
    plan = build_plan(("tests.test_a::t1", "unmappable"))
    assert plan.selected_ids == ("tests/test_a.py::t1",)
    import sys
    assert plan.full_command == [sys.executable, "-m", "pytest"]


def test_run_command_dry_run(capsys, tmp_path, monkeypatch):
    """friction run without --exec prints both commands; runs nothing."""
    from friction import cli as C
    d = tmp_path / "r"; d.mkdir()
    (d / "core.py").write_text("def compute(x):\n    return x + 1\n")
    (d / "test_core.py").write_text(
        "from core import compute\n\ndef test_helper():\n"
        "    assert compute(1) == 2\n")
    code = C.main(["run", "--repo", str(d), "--changed", "core.py"])
    out = capsys.readouterr().out
    assert code in (0, 1)
    assert "python -m pytest test_core.py::test_helper" in out
    assert "fallback" in out


def test_run_exec_reports_pytests_own_exit(capsys, tmp_path):
    """--exec actually runs pytest and passes ITS exit code through (0 pass)."""
    from friction import cli as C
    d = tmp_path / "r2"; d.mkdir()
    (d / "core.py").write_text("def compute(x):\n    return x + 1\n")
    (d / "test_core.py").write_text(
        "from core import compute\n\ndef test_helper():\n"
        "    assert compute(1) == 2\n")
    code = C.main(["run", "--repo", str(d), "--changed", "core.py",
                   "--exec"])
    out = capsys.readouterr().out
    assert code == 0                      # the selected few pass
    assert "executed : exit 0" in out


