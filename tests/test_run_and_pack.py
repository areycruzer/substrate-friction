def test_evidence_chains_present(tmp_path, monkeypatch):
    """The walk now ships the change→test chain for selected tests."""
    import friction.triage as T
    mini = tmp_path / "m"; mini.mkdir()
    (mini / "core.py").write_text(
        "def compute(x):\n    return x + 1\n\ndef helper(x):\n"
        "    return compute(x)\n")
    (mini / "test_core.py").write_text(
        "from core import helper\n\ndef test_helper():\n"
        "    assert helper(1) == 2\n")

    def fake_gh(path, token=None):
        if "/files" in path:
            return [{"filename": "core.py", "status": "modified"}]
        raise AssertionError(path)

    def fake_clone(slug, dest, pr_number=None, branch=None):
        for f in mini.iterdir():
            (dest / f.name).write_text(f.read_text(), encoding="utf-8")

    monkeypatch.setattr(T, "_gh", fake_gh)
    monkeypatch.setattr(T, "_shallow_clone", fake_clone)
    r = T.triage("https://github.com/o/r/pull/3")
    assert r.gate is not None and r.gate.evidence
    chain = next(iter(r.gate.evidence.values()))
    assert chain[0].startswith("core") and chain[-1].startswith("test_core")
    md = T.render_markdown(r)
    assert "chain:" in md and "snapshot:" in md


