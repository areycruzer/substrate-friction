def test_verify_certificate(capsys, tmp_path):
    from friction import cli as C
    cert = tmp_path / "cert.json"
    code = C.main(["verify", "--certificate", str(cert)])
    capsys.readouterr()
    assert code == 0
    d = json.loads(cert.read_text())
    assert d["figures"]["arm_b"] == "24/44"
    assert len(d["gate_results_sha256"]) == 64


